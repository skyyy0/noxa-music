package com.example.ui.theme

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

/**
 * Type scale for NOXA.
 *
 * Hierarchy is built from *contrast between sizes and weights*, not from
 * making every heading the heaviest weight available: display text stays
 * tight and confident (Bold with negative tracking), while labels drop to
 * Medium with positive tracking so small caps-style text breathes.
 *
 * Every Material3 role is defined here on purpose. An undefined role falls
 * back to the stock Material default — a different family rhythm and default
 * sizes — which silently breaks the scale the moment a Material component
 * picks it up. Full coverage means `MaterialTheme.typography.*` is always
 * safe to reach for, and callers never need a hardcoded `fontSize`.
 *
 * Role → use in the app:
 *  - display  : one statement per screen (artist name, year in Wrapped).
 *  - headline : page/hero titles.
 *  - title    : section and card titles, row primaries.
 *  - body     : prose, chat, lyrics, descriptions.
 *  - label    : eyebrows, chips, buttons, metadata — tracked out to read as
 *               a label rather than shrunken body copy.
 */
val Typography = Typography(
    displayLarge = TextStyle(
        fontFamily = FontFamily.SansSerif,
        fontWeight = FontWeight.Bold,
        fontSize = 36.sp,
        lineHeight = 40.sp,
        letterSpacing = (-0.9).sp
    ),
    displayMedium = TextStyle(
        fontFamily = FontFamily.SansSerif,
        fontWeight = FontWeight.Bold,
        fontSize = 28.sp,
        lineHeight = 33.sp,
        letterSpacing = (-0.6).sp
    ),
    displaySmall = TextStyle(
        fontFamily = FontFamily.SansSerif,
        fontWeight = FontWeight.Bold,
        fontSize = 24.sp,
        lineHeight = 29.sp,
        letterSpacing = (-0.5).sp
    ),
    headlineLarge = TextStyle(
        fontFamily = FontFamily.SansSerif,
        fontWeight = FontWeight.Bold,
        fontSize = 26.sp,
        lineHeight = 31.sp,
        letterSpacing = (-0.4).sp
    ),
    headlineMedium = TextStyle(
